-- The users table exactly as Hibernate used to create it.
-- IF NOT EXISTS: on a database that already has the table this does nothing,
-- on a brand-new database it creates it. Never edit a migration that has run;
-- add a new V<n>__ file instead.
CREATE TABLE IF NOT EXISTS users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password VARCHAR(255) NOT NULL,
    role     VARCHAR(255) NOT NULL,
    username VARCHAR(255) NOT NULL UNIQUE
);
