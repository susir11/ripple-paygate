-- The payments table exactly as Hibernate used to create it.
-- IF NOT EXISTS: on a database that already has the table this does nothing,
-- on a brand-new database it creates it. Never edit a migration that has run;
-- add a new V<n>__ file instead.
CREATE TABLE IF NOT EXISTS payments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount         DOUBLE PRECISION,
    status         VARCHAR(255),
    transaction_id VARCHAR(255),
    ref_id         VARCHAR(255)
);
